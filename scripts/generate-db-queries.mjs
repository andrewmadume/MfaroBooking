import ts from 'typescript';
import {readFileSync,writeFileSync} from 'node:fs';
const files=['app/api/[...path]/route.ts','lib/db.ts','lib/seed.ts','lib/scheduling.ts','lib/integrations.ts'];
const queries=new Set(['SELECT 1 AS connected']);
for(const file of files){
 const tree=ts.createSourceFile(file,readFileSync(file,'utf8'),ts.ScriptTarget.Latest,true);
 const constants=new Map();
 function value(node){
  if(!node)return undefined;
  if(ts.isStringLiteral(node)||ts.isNoSubstitutionTemplateLiteral(node))return node.text;
  if(ts.isIdentifier(node))return constants.get(node.text);
  if(ts.isBinaryExpression(node)&&node.operatorToken.kind===ts.SyntaxKind.PlusToken){const a=value(node.left),b=value(node.right);if(a!==undefined&&b!==undefined)return a+b;}
  if(ts.isTemplateExpression(node)){let text=node.head.text;for(const span of node.templateSpans){const expression=value(span.expression);if(expression===undefined)return undefined;text+=expression+span.literal.text;}return text;}
 }
 function collect(node){if(ts.isVariableDeclaration(node)&&ts.isIdentifier(node.name)){const v=value(node.initializer);if(v!==undefined)constants.set(node.name.text,v);}ts.forEachChild(node,collect);}
 collect(tree);collect(tree);
 function inspect(node){if(ts.isCallExpression(node)){const name=ts.isIdentifier(node.expression)?node.expression.text:ts.isPropertyAccessExpression(node.expression)?node.expression.name.text:'';if(['one','all','run','prepare'].includes(name)){const query=value(node.arguments[0]);if(query&&/^\s*(SELECT|INSERT|UPDATE|DELETE)\b/i.test(query))queries.add(query.trim());}}ts.forEachChild(node,inspect);}
 inspect(tree);
}
writeFileSync('supabase/functions/mfarobooking-db/allowed.ts','// Generated by npm run db:queries. Redeploy the Edge Function after SQL changes.\nexport const approvedQueries = new Set('+JSON.stringify([...queries].sort(),null,2)+');\n');
console.log(`Approved ${queries.size} fixed application query templates.`);
